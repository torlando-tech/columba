package network.columba.app.rns.host.persistence

import network.columba.app.domain.model.SignatureStatus
import network.reticulum.common.hexToByteArray
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

class LxmfSignatureVerifierTest {
    @Test
    fun `Python signed message verifies with and without its unsigned stamp`() {
        assertEquals(SignatureStatus.VERIFIED, verify(PythonLxmfFixture.wire))
        assertEquals(SignatureStatus.VERIFIED, verify(PythonLxmfFixture.stampedWire))
    }

    @Test
    fun `stamped nonminimal encodings normalize exactly as the upstream receiver`() {
        assertEquals(SignatureStatus.VERIFIED, verify(PythonLxmfFixture.nonminimalStampedWire))
    }

    @Test
    fun `signature from a different identity is invalid not unknown`() {
        assertEquals(SignatureStatus.INVALID, verify(PythonLxmfFixture.forgedWire))
    }

    @Test
    fun `unrelated keys and evidence for another message or recipient are not verification results`() {
        assertNull(verify(PythonLxmfFixture.wire, publicKey = ByteArray(64)))
        assertNull(verify(PythonLxmfFixture.wire, messageHash = "00".repeat(32)))
        assertNull(verify(PythonLxmfFixture.wire, destinationHash = "00".repeat(16)))
        assertNull(verify(byteArrayOf(1, 2, 3)))
    }

    private fun verify(
        evidence: ByteArray,
        publicKey: ByteArray = PythonLxmfFixture.publicKey,
        messageHash: String = PythonLxmfFixture.messageHash,
        destinationHash: String = PythonLxmfFixture.destination,
    ) = LxmfSignatureVerifier.verify(evidence, messageHash, PythonLxmfFixture.source, destinationHash, publicKey)
}

